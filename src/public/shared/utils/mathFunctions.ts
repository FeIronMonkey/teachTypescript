function add(a: number, b: number): number {
  return a + b;
}

function subtract(a: number, b: number): number {
  return a - b;
}

function multiply(a: number, b: number): number {
  return a * b;
}

function divide(a: number, b: number): number {
  return a / b;
}

function isLessThan(a: number, b: number): boolean {
  return a < b;
}

function isGreaterThan(a: number, b: number): boolean {
  return a > b;
}

function areEqual(a: number, b: number): boolean {
  return a === b;
}

export { add, subtract, multiply, divide, isLessThan, isGreaterThan, areEqual };
